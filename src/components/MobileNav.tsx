export default function MobileNav() {
  const pathname = usePathname();

  return (
    <div className="fixed bottom-0 left-0 right-0 z-40 sm:hidden bg-white/95 dark:bg-[#111111]/95 backdrop-blur border-t border-gray-100 dark:border-gray-800 pb-4">
      <div className="flex items-stretch justify-around">
        {navItems.map(({ href, label, icon }) => {
          // Exact match for home; prefix match for all other sections so that
          // e.g. /concepts?view=az and /guide/concepts/the-center both keep
          // the Concepts tab active.
          const isActive =
            href === '/'
              ? pathname === '/'
              : pathname === href ||
                pathname.startsWith(href + '/') ||
                pathname.startsWith(href + '?') ||
                // concept-page detail URLs still live under /guide/concepts
                (href === '/concepts' && pathname.startsWith('/guide/concepts'));
          return (
            <Link
              key={href}
              href={href}
              className={`flex flex-col items-center gap-0.5 pt-2 pb-1 px-3 flex-1 transition-colors ${
                isActive
                  ? 'text-gray-900 dark:text-white'
                  : 'text-gray-400 dark:text-gray-500'
              }`}
            >
              {icon}
              <span className="text-[10px] leading-tight">{label}</span>
            </Link>
          );
        })}
      </div>
    </div>
  );
}
